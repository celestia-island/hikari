// Compile the boot panel's two stylesheet entries into generated modules:
//
//   src/plugins/boot-landing.scss          -> src/plugins/bootLandingCss.mjs
//   src/plugins/boot-landing-details.scss  -> src/plugins/bootLandingDetailsCss.mjs
//
// TWO sheets, because the panel has two halves with different audiences. The
// landing sheet is embedded in EVERY generated script (the card is the whole
// panel), so it must not grow: the boot-recovery module documents BYTE-COMPAT
// — a host that configures none of the newer options keeps a byte-identical
// script it can keep hashing into its CSP. The details sheet only exists when
// the host opts in with `copy.rawDetailsLabel`, so it is emitted as its own
// module and embedded only then. Adding those rules to the landing entry
// instead would have been one line shorter here and a changed CSP hash for
// every host there.
//
// The boot-recovery plugin runs inside a host's vite.config.*, where Node
// cannot compile SCSS (sass is a devDependency, and the published package
// carries no build step). The generated modules therefore carry the compiled
// sheets as strings; bootLandingCss.test.ts recompiles both entries and fails
// when the checked-in modules no longer match, so the panel cannot drift from
// the component sheets they mirror.
//
// Usage (from packages/vue): pnpm run gen:boot-landing-css

import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileSync } from "node:fs";

import * as sass from "sass";

const HERE = dirname(fileURLToPath(import.meta.url));
/** packages/vue */
const VUE_DIR = resolve(HERE, "..");
const SRC_DIR = resolve(VUE_DIR, "src");

/** Compile one entry exactly the way the drift test does. */
function compileEntry(entryPath) {
  const compiled = sass.compile(entryPath, {
    loadPaths: [SRC_DIR, resolve(SRC_DIR, "styles"), resolve(SRC_DIR, "styles", "theme")],
    style: "compressed",
    // The legacy Gen-1 sheets still use the import bridge; not this file's job.
    silenceDeprecations: ["import", "global-builtin", "legacy-js-api"],
  });
  // @charset is meaningless inside the inline <style> the panel appends; the
  // generated script is ASCII-only through the plugin's jsonAscii anyway.
  return compiled.css.replace(/^@charset "UTF-8";/, "").trim();
}

/** JSON string literal safe to paste into the generated module. */
function literal(css) {
  return JSON.stringify(css);
}

/** Reject a sheet that could break the inline <script> or the CSP hash. */
function assertAsciiCss(label, css) {
  for (let i = 0; i < css.length; i += 1) {
    if (css.charCodeAt(i) > 0x7f) {
      throw new Error(
        label +
          " compiled to non-ASCII text at index " +
          i +
          " — the boot script inlines this sheet and must stay ASCII",
      );
    }
  }
}

const HEADER = `// AI-generated: developed with the DeepSeek Harness agent (model
// DeepSeek-V4.1-Flash) directed and reviewed by langyo — SySL-1.0 §2.3
// disclosure.
//
// @generated by scripts/gen-boot-landing-css.mjs — DO NOT EDIT.
// Regenerate with (from packages/vue): pnpm run gen:boot-landing-css
//
`;

const landingCss = compileEntry(resolve(SRC_DIR, "plugins/boot-landing.scss"));
assertAsciiCss("boot-landing.scss", landingCss);
const landingOut = resolve(SRC_DIR, "plugins/bootLandingCss.mjs");
const landingSource =
  HEADER +
  `// The compiled src/plugins/boot-landing.scss: hikari's own seed channels, L2
// scale tokens, HkErrorLanding card and HkButton chrome, in the one file the
// pre-boot failure panel inlines. The panel is the pre-framework twin of
// HkErrorLanding, so it ships the component's real stylesheet instead of a
// hand-copied palette. bootLandingCss.test.ts recompiles the entry and fails
// on drift.
export const BOOT_LANDING_CSS = ` +
  literal(landingCss) +
  `;
`;
writeFileSync(landingOut, landingSource, "utf8");

const detailsCss = compileEntry(resolve(SRC_DIR, "plugins/boot-landing-details.scss"));
assertAsciiCss("boot-landing-details.scss", detailsCss);
const detailsOut = resolve(SRC_DIR, "plugins/bootLandingDetailsCss.mjs");
const detailsSource =
  HEADER +
  `// The compiled src/plugins/boot-landing-details.scss: HkJsonTree's tree
// classes and hikari's overlay-scrollbar chrome, inlined by the pre-boot
// failure panel ONLY when the host opts into the raw-details pane
// (the host's copy.rawDetailsLabel). Kept out of BOOT_LANDING_CSS on
// purpose: that sheet rides every generated script, and the module's
// BYTE-COMPAT contract keeps an unconfigured host's script byte-identical.
// bootLandingCss.test.ts recompiles the entry and fails on drift.
export const BOOT_LANDING_DETAILS_CSS = ` +
  literal(detailsCss) +
  `;
`;
writeFileSync(detailsOut, detailsSource, "utf8");

console.log(
  "wrote " +
    landingOut +
    " (" +
    landingCss.length +
    " CSS bytes, " +
    landingSource.length +
    " module bytes)",
);
console.log(
  "wrote " +
    detailsOut +
    " (" +
    detailsCss.length +
    " CSS bytes, " +
    detailsSource.length +
    " module bytes)",
);
