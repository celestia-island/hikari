import {
  computed,
  defineComponent,
  onBeforeUnmount,
  onMounted,
  ref,
  watch,
  type PropType,
} from "vue";

import { useI18n } from "../i18n/context";
import {
  generateSlidePath,
  slideAdvanceT,
  slidePathLength,
  slidePixelPoints,
  slidePointAtT,
  type SlidePath,
  type SlidePoint,
} from "./slideConfirmPath";
import "./HkSlideConfirm.scss";

/** Drag progress at which the confirmation fires (the lane's very end;
 *  a hair of tolerance for float rounding along the final run). */
const COMPLETE_T = 0.995;

/** The lane keeps a knob-radius margin from the track edges. */
const TRACK_PAD = 24;

/** Pointer corridor: half a lane's height (+ a little slack) — the knob
 *  must be traced, not approximated with a straight chord across the
 *  turns (the corridor is deliberately too narrow to cut a corner). */
function corridorRadius(innerHeight: number): number {
  return innerHeight / 6 + 4;
}

interface TrackBox {
  width: number;
  height: number;
  left: number;
  top: number;
}

/**
 * HkSlideConfirm — the fat slide-to-confirm: a three-standard-row block
 * carrying an orthogonal lane with RANDOM right-angle turns; the user
 * grabs the knob and drags it along the lane from the left edge to the
 * right edge. Releasing before the end — or dragging off the lane's
 * corridor — snaps the knob back to the start at once. Reaching the end
 * emits `confirm` once.
 *
 * 2026-11-19 user direction (the workspace delete confirmation): the
 * straight slide-to-confirm family is everywhere; this one is the
 * captcha-shaped cousin — a traced route, not a straight pull — as a
 * general business component. The route is random per mount (captcha
 * property); a `seed` prop pins it for tests and snapshots.
 *
 * Mechanics:
 *  · the lane is generated by `generateSlidePath` (≥3 random 90° turns
 *    through three lanes; pure module, jsdom-tested separately);
 *  · following = monotonic arc-length advance: the knob jumps to the
 *    furthest lane point within the pointer corridor; a pointer that
 *    leaves the corridor (corner-cutting) is a failed attempt;
 *  · release / pointercancel / corridor exit before the end → the knob
 *    snaps back to the start (transitioned; reduced-motion snaps at once);
 *  · keyboard: the knob is a slider handle — arrows walk the lane
 *    (Right/Up advance, Left/Down retreat, Home resets), reaching the end
 *    fires `confirm`; AT users get the same confirmation without a
 *    pointer.
 *
 * The component carries zero transport and zero business semantics: hosts
 * render it inside their own confirmation surface and react to `confirm`.
 */
export default defineComponent({
  name: "HkSlideConfirm",
  props: {
    /** Accessible name / the instruction inside the track while idle.
     *  Defaults to the localized "Hold the knob and drag along the lane
     *  to the right edge". */
    label: { type: String, default: undefined },
    /** Text flashed in the track after the lane is completed. */
    successLabel: { type: String, default: undefined },
    disabled: { type: Boolean, default: false },
    /** Pins the random route (tests); absent = fresh random route per
     *  mount. A change regenerates the lane and resets progress. */
    seed: { type: Number, default: undefined },
  },
  emits: {
    /** Fired ONCE when the knob completes the lane. The component resets
     *  on regeneration/mount only — the host closes its surface. */
    confirm: () => true,
  },
  setup(props, { emit }) {
    const { t } = useI18n();

    const rootRef = ref<HTMLElement | null>(null);
    /** Knob element — the pointer-capture and slider-handle host. */
    const knobRef = ref<HTMLElement | null>(null);

    const path = ref<SlidePath>(generateSlidePath((props.seed ?? (Math.random() * 0xffffffff)) >>> 0));
    const regenerate = () => {
      path.value = generateSlidePath((props.seed ?? (Math.random() * 0xffffffff)) >>> 0);
      progress.value = 0;
      status.value = "idle";
    };
    watch(() => props.seed, regenerate);

    /** Arc-length progress 0..1 along the lane. */
    const progress = ref(0);
    type SlideStatus = "idle" | "dragging" | "snapping" | "done";
    const status = ref<SlideStatus>("idle");

    const dragging = () => status.value === "dragging";

    /** The measured track box — reactive so the lane and knob re-map when
     *  it lands (mount) or moves (resize). jsdom measures 0×0 until a
     *  test injects a rect. */
    const box = ref<TrackBox>({ width: 0, height: 0, left: 0, top: 0 });
    function measure() {
      const rect = rootRef.value?.getBoundingClientRect();
      if (rect && rect.width > 0) {
        box.value = { width: rect.width, height: rect.height, left: rect.left, top: rect.top };
      }
    }
    function onWindowResize() {
      box.value = { width: 0, height: 0, left: 0, top: 0 };
      measure();
    }
    onMounted(() => {
      measure();
      window.addEventListener("resize", onWindowResize);
    });
    onBeforeUnmount(() => {
      window.removeEventListener("resize", onWindowResize);
      if (snapTimer) clearTimeout(snapTimer);
    });

    function pixelPolyline(): SlidePoint[] {
      const b = box.value;
      return slidePixelPoints(
        path.value.points,
        Math.max(0, b.width - TRACK_PAD * 2),
        Math.max(0, b.height - TRACK_PAD * 2),
      );
    }

    /** Knob center in TRACK-LOCAL px (the transform target). */
    const knobPos = computed<SlidePoint>(() => slidePointAtT(pixelPolyline(), progress.value));

    /** Lane polyline in px (SVG points space; the svg is positioned at
     *  TRACK_PAD inset with a matching viewBox). */
    const laneBox = computed(() => {
      const b = box.value;
      const w = Math.max(0, b.width - TRACK_PAD * 2);
      const h = Math.max(0, b.height - TRACK_PAD * 2);
      return { w, h };
    });
    const laneSvgPoints = computed(() => {
      const { w, h } = laneBox.value;
      return slidePixelPoints(path.value.points, w, h)
        .map((p) => `${p.x.toFixed(1)},${p.y.toFixed(1)}`)
        .join(" ");
    });

    let snapTimer: ReturnType<typeof setTimeout> | null = null;
    function snapBack() {
      status.value = "snapping";
      progress.value = 0;
      if (snapTimer) clearTimeout(snapTimer);
      // The transition (SCSS) carries the visual return; the state resets
      // after it so the next grab starts clean.
      snapTimer = setTimeout(() => {
        status.value = "idle";
      }, 260);
    }

    function complete() {
      if (status.value === "done") return;
      status.value = "done";
      emit("confirm");
    }

    function onKnobPointerdown(e: PointerEvent) {
      if (props.disabled || status.value === "done") return;
      try {
        knobRef.value?.setPointerCapture?.(e.pointerId);
      } catch {
        // jsdom/test environments have no capture — the move/up wiring
        // below is on the knob itself and still fires.
      }
      box.value = { width: 0, height: 0, left: 0, top: 0 }; // re-measure per gesture
      measure();
      status.value = "dragging";
    }

    function onKnobPointermove(e: PointerEvent) {
      if (status.value !== "dragging") return;
      const b = box.value;
      const pixel = pixelPolyline();
      const total = slidePathLength(pixel);
      if (total <= 0) return;
      // The pointer arrives in TRACK-LOCAL px; the lane lives in the
      // TRACK_PAD-inset frame — compare in the lane's own frame.
      const px = e.clientX - b.left - TRACK_PAD;
      const py = e.clientY - b.top - TRACK_PAD;
      const next = slideAdvanceT(pixel, progress.value, px, py, corridorRadius(b.height));
      if (next === null) {
        // Left the corridor: corner-cutting is a failed attempt.
        snapBack();
        return;
      }
      progress.value = next;
      if (next >= COMPLETE_T) complete();
    }

    function onKnobPointerup() {
      if (status.value !== "dragging") return;
      if (progress.value < COMPLETE_T) snapBack();
    }

    /** Keyboard walk step: one lane-step ≈ 1/24 of the lane (each arrow
     *  press makes visible progress; ~24 presses traverse the full lane,
     *  and the turns come for free from the arc-length parameter). */
    const KEY_STEP = 1 / 24;
    function onKnobKeydown(e: KeyboardEvent) {
      if (props.disabled || status.value === "done") return;
      let handled = true;
      switch (e.key) {
        case "ArrowRight":
        case "ArrowUp":
          progress.value = Math.min(1, progress.value + KEY_STEP);
          break;
        case "ArrowLeft":
        case "ArrowDown":
          progress.value = Math.max(0, progress.value - KEY_STEP);
          break;
        case "Home":
          progress.value = 0;
          break;
        case "End":
          progress.value = 1;
          break;
        default:
          handled = false;
      }
      if (handled) {
        e.preventDefault();
        if (progress.value >= COMPLETE_T) complete();
      }
    }

    const idleLabel = computed(
      () => props.label ?? t("hikari::slideConfirm.drag", "Hold the knob and drag along the lane to the right edge"),
    );
    const doneLabel = computed(
      () => props.successLabel ?? t("hikari::slideConfirm.success", "Confirmed"),
    );

    return () => {
      const done = status.value === "done";
      const { w, h } = laneBox.value;
      const pos = knobPos.value;
      return (
        <div
          class={{
            "hk-slide-confirm": true,
            "is-dragging": status.value === "dragging",
            "is-snapping": status.value === "snapping",
            "is-done": done,
            "is-disabled": props.disabled,
          }}
          ref={rootRef}
        >
          {/* The lane: px-space polyline inside a TRACK_PAD-inset svg —
              the knob rides the same coordinate frame. */}
          <svg
            class="hk-slide-confirm-lane"
            aria-hidden="true"
            style={{ inset: `${TRACK_PAD}px` }}
            width={w}
            height={h}
            viewBox={`0 0 ${w} ${h}`}
          >
            <polyline points={laneSvgPoints.value} class={{ "hk-slide-confirm-lane-path": true, "is-done": done }} />
          </svg>
          {!done ? (
            <span class="hk-slide-confirm-label" aria-hidden="true">
              {idleLabel.value}
            </span>
          ) : (
            <span class="hk-slide-confirm-done-label" aria-hidden="true">
              {doneLabel.value}
            </span>
          )}
          <div
            ref={knobRef}
            class={{ "hk-slide-confirm-knob": true, "is-done": done }}
            role="slider"
            tabindex={props.disabled ? -1 : 0}
            aria-disabled={props.disabled}
            aria-label={done ? doneLabel.value : idleLabel.value}
            aria-valuemin={0}
            aria-valuemax={100}
            aria-valuenow={Math.round(progress.value * 100)}
            style={{
              // The lane frame is inset by TRACK_PAD; the knob (absolutely
              // parked at the track's corner) rides it from there.
              transform: `translate(${(TRACK_PAD + pos.x).toFixed(1)}px, ${(TRACK_PAD + pos.y).toFixed(1)}px)`,
            }}
            onPointerdown={onKnobPointerdown}
            onPointermove={onKnobPointermove}
            onPointerup={onKnobPointerup}
            onPointercancel={onKnobPointerup}
            onKeydown={onKnobKeydown}
          >
            <span class="hk-slide-confirm-knob-grip" aria-hidden="true" />
          </div>
        </div>
      );
    };
  },
});
